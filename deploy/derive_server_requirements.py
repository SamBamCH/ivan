#!/usr/bin/env python3
"""
Regenerate requirements-server.txt from what the NFL pre-lock path actually needs.

Two probes, both run inside the working dev venv:
  1. import every module on the pre-lock path and the web UI;
  2. unpickle every model file under data/nfl/models (skipping archive/), because
     scikit-learn and friends are only imported when a pickle is loaded, which an
     import walk cannot see.
Newly imported top-level modules are mapped to installed distributions and pinned at
the installed version. Run it after changing imports or retraining models with a new
library, then `pip install -r requirements-server.txt` on the server.

    venv/bin/python deploy/derive_server_requirements.py
"""
import importlib
import importlib.metadata as md
import pickle
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "requirements-server.txt"
MODELS = ROOT / "data" / "nfl" / "models"

MODULES = [
    "ivan.core.config", "ivan.database.session", "ivan.sports.nfl.models", "ivan.sports.nfl.paths",
    "ivan.sports.nfl.generate_lineups_logic", "ivan.sports.nfl.sample_field", "ivan.sports.nfl.simulate_contest",
    "ivan.sports.nfl.correlated_samples", "ivan.sports.nfl.choose", "ivan.sports.nfl.ownership",
    "ivan.sports.nfl.refactor.player", "ivan.sports.common.draftkings", "ivan.sports.common.odds",
    "ivan.web.app", "fastapi", "uvicorn", "jinja2", "multipart", "rich.progress", "pandas", "dotenv",
]
# uvicorn[standard] extras; plain uvicorn is enough for a LAN UI
EXCLUDE = {"uvloop", "httptools", "watchfiles", "websockets", "ujson", "ivan"}


def main() -> int:
    before = set(sys.modules)
    for m in MODULES:
        importlib.import_module(m)
    import joblib
    n_pickles = 0
    for p in sorted(MODELS.rglob("*.pkl")):
        if "archive" in p.parts:
            continue
        try:
            joblib.load(p)
        except Exception:
            with open(p, "rb") as f:
                pickle.load(f)
        n_pickles += 1

    tops = {m.split(".")[0] for m in set(sys.modules) - before}
    tops |= {"fastapi", "uvicorn", "jinja2", "multipart", "rich", "pandas", "dotenv"}
    dist_of, stdlib = md.packages_distributions(), set(sys.stdlib_module_names)
    dists = {d for t in tops if t not in stdlib and not t.startswith("_") for d in dist_of.get(t, [])} - EXCLUDE
    lines = [f"{d}=={md.version(d)}" for d in sorted(dists, key=str.lower)]
    OUT.write_text(
        "# Thin install for the server: the NFL pre-lock path (ingest -> generate -> sim -> choose)\n"
        "# plus the web UI. GENERATED by deploy/derive_server_requirements.py from what those modules\n"
        "# import and what the model pickles need at load time, pinned at the dev venv's versions.\n"
        "# No Selenium, no other sports' API clients, no model-training extras.\n" + "\n".join(lines) + "\n")
    print(f"{OUT.name}: {len(lines)} packages from {len(MODULES)} modules + {n_pickles} pickles")
    return 0


if __name__ == "__main__":
    sys.exit(main())
